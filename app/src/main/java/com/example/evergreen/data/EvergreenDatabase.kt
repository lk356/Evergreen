/** Stores [EndReason] as its name rather than its position in the enum. */
class Converters {
    @TypeConverter
    fun toEndReason(value: String?): EndReason? =
        value?.let { name -> runCatching { EndReason.valueOf(name) }.getOrDefault(EndReason.UNKNOWN) }

    @TypeConverter
    fun fromEndReason(reason: EndReason?): String? = reason?.name

    @TypeConverter
    fun toLikeEventType(value: String?): LikeEventType? =
        value?.let { name -> runCatching { LikeEventType.valueOf(name) }.getOrNull() }

    @TypeConverter
    fun fromLikeEventType(event: LikeEventType?): String? = event?.name

    /**
     * Same discipline as [toEndReason]: an unrecognised name falls back to
     * [SegmentSource.CAPTURE] rather than throwing, so a row written by a later
     * build cannot stop an earlier one reading the table.
     */
    @TypeConverter
    fun toSegmentSource(value: String?): SegmentSource? =
        value?.let { name -> runCatching { SegmentSource.valueOf(name) }.getOrDefault(SegmentSource.CAPTURE) }

    @TypeConverter
    fun fromSegmentSource(source: SegmentSource?): String? = source?.name

    @TypeConverter
    fun toMembershipReason(value: String?): MembershipReason? =
        value?.let { name -> runCatching { MembershipReason.valueOf(name) }.getOrNull() }

    @TypeConverter
    fun fromMembershipReason(reason: MembershipReason?): String? = reason?.name
}

/**
 * The schema version, as one named constant.
 *
 * Top-level rather than in the companion because an annotation argument has to
 * be a compile-time constant and a class cannot refer to its own companion
 * from its own annotation. It exists so that the mirror import can refuse a
 * backup taken under a different schema by comparing against this number
 * rather than a literal written out a second time somewhere else.
 */
const val EVERGREEN_SCHEMA_VERSION = 7

/**
 * v6 to v7: `listening_segments.originRowId`, and the unique index over
 * `(deviceId, originRowId)` that makes applying a delta batch twice a no-op.
 *
 * **The one migration in this project written by hand, and the reason is
 * 77,518 rows.** Every other migration here is generated by Room against the
 * committed schema JSON, which is the right default: a generated migration
 * cannot disagree with the schema it was generated from. This one is not,
 * because of what Room's generator produces for this particular change.
 *
 * Adding the column on its own generates exactly what SQLite is good at:
 *
 * ```
 * ALTER TABLE listening_segments ADD COLUMN originRowId INTEGER DEFAULT NULL
 * ```
 *
 * which is a change to the stored schema text and nothing else — not one row
 * is read or rewritten, whatever the table's size. But adding an *index* puts
 * the table into Room's "complex change" bucket, and the generated migration
 * then creates a new table, copies every row into it, drops the old one and
 * rebuilds all six indices. That is what the v2 and v4 migrations did, and it
 * was the right trade there because those changes really did need a rebuild
 * (a foreign key's delete rule, and a column's nullability, neither of which
 * SQLite can alter in place). Here nothing needs it. The difference on the
 * NW-A307 — a low-powered device holding six years of real listening — is
 * between copying 77,518 rows and copying none.
 *
 * So: two statements, in the order SQLite wants them.
 *
 * **The index cannot fail on the existing data.** Every row gets NULL, and a
 * SQLite unique index treats two NULLs as different values rather than as a
 * collision. That is the same rule [ListeningSegmentEntity.originRowId] leans
 * on to leave `capture/` untouched, and it is worth knowing that it is doing
 * two jobs.
 *
 * Room still validates the result against `schemas/7.json` when it opens the
 * database, so a hand-written migration that produced the wrong shape would be
 * refused at the first open rather than discovered later. `EvergreenMigrationTest`
 * pins it against a populated v6 database as well.
 */
val MIGRATION_6_7 = object : Migration(6, 7) {
    override fun migrate(connection: SQLiteConnection) {
        connection.execSQL(
            "ALTER TABLE `listening_segments` ADD COLUMN `originRowId` INTEGER DEFAULT NULL",
        )
        connection.execSQL(
            "CREATE UNIQUE INDEX IF NOT EXISTS `index_listening_segments_deviceId_originRowId` " +
                "ON `listening_segments` (`deviceId`, `originRowId`)",
        )
    }
}

/**
 * The app's local database, and the source of truth for everything Evergreen
 * knows. Streaming services are sync targets, never the authority.
 *
 * `exportSchema = true` from version 1 onwards: each build writes a JSON
 * description of this schema to `app/schemas/`, which is committed. Future
 * migrations can then be generated and tested against the real previous schema
 * instead of being hand-written from memory.
 *
 * The database file is excluded from cloud backup and device-to-device transfer
 * by `data_extraction_rules.xml`; nothing here may leave the device.
 */
@Database(
    entities = [
        TrackEntity::class,
        ServiceTrackEntity::class,
        ListeningSegmentEntity::class,
        LikeEntity::class,
        LikeEventEntity::class,
        SyncStateEntity::class,
        TrackMergeEntity::class,
        ScoreEntity::class,
        EvergreenMembershipEntity::class,
        SnapshotEntity::class,
        SnapshotEntryEntity::class,
        ParameterHistoryEntity::class,
    ],
    version = EVERGREEN_SCHEMA_VERSION,
    exportSchema = true,
    autoMigrations = [
        // Generated by Room against the committed schemas/1.json rather than
        // written by hand. v2 changes three foreign keys from CASCADE/SET NULL
        // to RESTRICT, which SQLite cannot do in place — Room rebuilds the
        // affected tables and copies every row across. The copy is the step
        // where history could be lost, so EvergreenMigrationTest builds a
        // populated v1 database, migrates it, and asserts the segments survive.
        AutoMigration(from = 1, to = 2),
        // v3 only adds the track_merges audit table; no existing table is
        // touched and no row moves.
        AutoMigration(from = 2, to = 3),
        // v4 gives listening_segments its `source` and `sourceEndReason`
        // columns and makes the five position/seek columns nullable, so that
        // imported history can land in the same table capture writes to
        // (invariant 1b) without any column being filled with a made-up value.
        //
        // Changing nullability is not something SQLite can do in place, so
        // Room rebuilds the table and copies every row -- the same shape of
        // migration as v2, and the same place where history could be lost.
        // EvergreenMigrationTest builds a populated v3 database, migrates it,
        // and asserts every segment survives with its positions intact and
        // `source = CAPTURE`.
        AutoMigration(from = 3, to = 4),
        // v5 only adds tables -- the score cache, the Evergreen membership
        // record and the two snapshot tables. No existing table is touched and
        // no row moves, so unlike v2 and v4 there is nothing here that could
        // lose history. Split from v4 so that each migration is one idea with
        // one test.
        AutoMigration(from = 4, to = 5),
        // v6 adds `parameter_history` and nothing else. Like v5 it only adds a
        // table, so no existing row moves and there is nothing here that could
        // lose history -- but unlike the v5 tables, the one it adds is not a
        // cache. `scores` can be dropped and rebuilt; a parameter change that
        // was never recorded is gone. See ParameterHistoryEntity.
        AutoMigration(from = 5, to = 6),
        // v7 is deliberately NOT here. It is the one hand-written migration in
        // the project, and MIGRATION_6_7 below says why.
    ],
)
@TypeConverters(Converters::class)
abstract class EvergreenDatabase : RoomDatabase() {

    abstract fun dao(): EvergreenDao

    /** Phase 2's writes. Kept separate so the capture path's DAO is untouched. */
    abstract fun spotifyDao(): SpotifyDao

    /** Phase 3's scoring reads and writes, separate for the same reason. */
    abstract fun scoringDao(): ScoringDao

    /** The streaming-history import's reads and bookkeeping. */
    abstract fun importDao(): ImportDao

    companion object {
        private const val DB_NAME = "evergreen.db"

        @Volatile
        private var instance: EvergreenDatabase? = null

        /**
         * One instance per process. The capture service and the UI both reach
         * for this, and Room requires them to share a single handle.
         */
        fun get(context: Context): EvergreenDatabase =
            instance ?: synchronized(this) {
                instance ?: build(context.applicationContext).also { instance = it }
            }

        private fun build(context: Context): EvergreenDatabase =
            Room.databaseBuilder(context, EvergreenDatabase::class.java, DB_NAME)
                // Write-ahead logging lets the debug screen keep reading while
                // the capture service writes, instead of the two blocking each
                // other. Room enables foreign-key enforcement on its own.
                .setJournalMode(JournalMode.WRITE_AHEAD_LOGGING)
                .addMigrations(MIGRATION_6_7)
                .build()

        /** Where the database file lives, for the one operation that replaces it. */
        fun fileFor(context: Context): File = context.getDatabasePath(DB_NAME)

        /**
         * A staging path beside the live database, for the same reason.
         *
         * In the *same directory* deliberately: the mirror import finishes with
         * a rename, and a rename is only atomic within one filesystem. Staging
         * in the cache directory would work on this device and silently stop
         * being atomic on a device that mounts it elsewhere.
         */
        fun stagingFileFor(context: Context): File =
            context.getDatabasePath("evergreen-mirror-staging.db")

        /**
         * The same, for a restore.
         *
         * A path of its own rather than sharing the one above. Both operations
         * are reachable from the same screen, both stage before they ask, and
         * one shared staging file is a way for "yes" to a restore to apply a
         * file that was staged for a mirror import — which is precisely the
         * confusion the two operations exist to keep apart.
         */
        fun restoreStagingFileFor(context: Context): File =
            context.getDatabasePath("evergreen-restore-staging.db")

        /**
         * Closes the database and forgets the instance, so the next [get]
         * opens whatever file is on disk now.
         *
         * Only the mirror import calls this. Everything holding the old handle
         * — the composables that captured it, the capture service's writer —
         * is either stopped first or fails safely and is rebuilt when the
         * screen is, which is why the import restarts the UI when it is done.
         */
        fun closeForReplacement() {
            synchronized(this) {
                instance?.close()
                instance = null
            }
        }
    }
}
