/**
 * Tests the migrations that rebuild `listening_segments`, against a real SQLite
 * database.
 *
 * The migrations themselves are generated by Room from the committed schema
 * JSON, not hand-written. What is *not* generated, and what these tests exist
 * for, is the guarantee that matters: both v2 and v4 change something SQLite
 * cannot alter in place — three foreign keys in v2, five columns' nullability
 * in v4 — so Room rebuilds the table and copies every row across. That copy is
 * the moment listening history could quietly disappear.
 *
 * So these tests are not "does the migration run"; Room's own validation covers
 * the shape. They are "is the data still there afterwards, unchanged".
 */
@RunWith(AndroidJUnit4::class)
class EvergreenMigrationTest {

    private companion object {
        const val TEST_DB = "migration-test.db"

        /**
         * Segment #12 from the Phase 1 device verification: *Electro Swingity*,
         * seeked to near the end and barely heard. Chosen deliberately — it is
         * the row where `endPositionMs` (99% of the track) and `listenedMs` (8%)
         * disagree most, so if the migration ever mangled a column by copying
         * them in the wrong order, this row would show it.
         */
        const val SEEKED_END_POSITION = 232_000L
        const val SEEKED_LISTENED = 19_000L
        const val SEEKED_DURATION = 234_000L
    }

    @get:Rule
    val helper = MigrationTestHelper(
        InstrumentationRegistry.getInstrumentation(),
        EvergreenDatabase::class.java,
    )

    /**
     * Builds a v1 database holding one canonical track, one Spotify service
     * identifier and two segments, then migrates it and reads everything back.
     */
    @Test
    fun migrate1To2_preservesExistingRows() {
        helper.createDatabase(TEST_DB, 1).use { db ->
            db.execSQL(
                """
                INSERT INTO tracks
                    (id, trackKey, title, artist, album, durationMs, firstSeenAt, lastSeenAt)
                VALUES (1, 'electro swingity|tonight we rise|singles', 'Electro Swingity',
                        'Tonight We Rise', 'Singles', $SEEKED_DURATION, 1000, 2000)
                """.trimIndent(),
            )
            db.execSQL(
                """
                INSERT INTO service_tracks
                    (id, trackId, service, serviceTrackId, isrc, durationMs, firstSeenAt, lastSeenAt)
                VALUES (1, 1, 'spotify', 'spotify:track:1xHutdgil2xlhdNLOL8Cr9', NULL,
                        $SEEKED_DURATION, 1000, 2000)
                """.trimIndent(),
            )
            // One segment carrying a service id, one without — the second
            // exercises the nullable side of the key that becomes RESTRICT.
            db.execSQL(
                """
                INSERT INTO listening_segments
                    (id, trackId, serviceTrackRowId, appPackage, deviceId, startedAtMs, endedAtMs,
                     startPositionMs, endPositionMs, listenedMs, trackDurationMs,
                     forwardSeekCount, seekedForwardMs, endReason, endJumpFromMs, endJumpToMs,
                     lastSampleAgeMs, createdAt)
                VALUES (1, 1, 1, 'com.spotify.music', 'test-device', 1000, 2000,
                        0, $SEEKED_END_POSITION, $SEEKED_LISTENED, $SEEKED_DURATION,
                        1, 180000, 'TRACK_CHANGE', NULL, NULL, 500, 2000)
                """.trimIndent(),
            )
            db.execSQL(
                """
                INSERT INTO listening_segments
                    (id, trackId, serviceTrackRowId, appPackage, deviceId, startedAtMs, endedAtMs,
                     startPositionMs, endPositionMs, listenedMs, trackDurationMs,
                     forwardSeekCount, seekedForwardMs, endReason, endJumpFromMs, endJumpToMs,
                     lastSampleAgeMs, createdAt)
                VALUES (2, 1, NULL, 'com.spotify.music', 'test-device', 3000, 4000,
                        0, 31250, 31250, $SEEKED_DURATION,
                        0, 0, 'POSITION_JUMP_BACK', 31250, 0, 31250, 4000)
                """.trimIndent(),
            )
        }

        // validateDroppedTables = true: fail if the migration leaves the
        // `_new_*` scratch tables behind rather than renaming them.
        val migrated = helper.runMigrationsAndValidate(TEST_DB, 2, true)

        migrated.query("SELECT COUNT(*) FROM listening_segments").use { c ->
            c.moveToFirst()
            assertEquals("both segments must survive the table rebuild", 2, c.getInt(0))
        }

        // Every column of the interesting segment, read back by name so a
        // reordered copy would fail rather than pass by coincidence.
        migrated.query(
            """
            SELECT trackId, serviceTrackRowId, appPackage, deviceId, startedAtMs, endedAtMs,
                   startPositionMs, endPositionMs, listenedMs, trackDurationMs,
                   forwardSeekCount, seekedForwardMs, endReason, endJumpFromMs, endJumpToMs,
                   lastSampleAgeMs, createdAt
              FROM listening_segments WHERE id = 1
            """.trimIndent(),
        ).use { c ->
            assertTrue(c.moveToFirst())
            assertEquals(1L, c.getLong(c.getColumnIndexOrThrow("trackId")))
            assertEquals(1L, c.getLong(c.getColumnIndexOrThrow("serviceTrackRowId")))
            assertEquals("com.spotify.music", c.getString(c.getColumnIndexOrThrow("appPackage")))
            assertEquals("test-device", c.getString(c.getColumnIndexOrThrow("deviceId")))
            assertEquals(
                "position reached must not be confused with time listened",
                SEEKED_END_POSITION,
                c.getLong(c.getColumnIndexOrThrow("endPositionMs")),
            )
            assertEquals(
                SEEKED_LISTENED,
                c.getLong(c.getColumnIndexOrThrow("listenedMs")),
            )
            assertEquals(SEEKED_DURATION, c.getLong(c.getColumnIndexOrThrow("trackDurationMs")))
            assertEquals(1, c.getInt(c.getColumnIndexOrThrow("forwardSeekCount")))
            assertEquals(180_000L, c.getLong(c.getColumnIndexOrThrow("seekedForwardMs")))
            assertEquals("TRACK_CHANGE", c.getString(c.getColumnIndexOrThrow("endReason")))
            assertEquals(500L, c.getLong(c.getColumnIndexOrThrow("lastSampleAgeMs")))
        }

        // The replay segment keeps its jump pair — the thing Phase 1 stores so
        // that Phase 3 can still choose a replay threshold.
        migrated.query(
            "SELECT endReason, endJumpFromMs, endJumpToMs, serviceTrackRowId " +
                "FROM listening_segments WHERE id = 2",
        ).use { c ->
            assertTrue(c.moveToFirst())
            assertEquals("POSITION_JUMP_BACK", c.getString(0))
            assertEquals(31_250L, c.getLong(1))
            assertEquals(0L, c.getLong(2))
            assertTrue("a segment with no service id must stay null", c.isNull(3))
        }

        // The service identifier and its canonical track survive too, and the
        // new ISRC bookkeeping columns default to "never looked up".
        migrated.query(
            "SELECT serviceTrackId, isrc, isrcLookupAt, isrcLookupAttempts, isrcLookupError " +
                "FROM service_tracks WHERE id = 1",
        ).use { c ->
            assertTrue(c.moveToFirst())
            assertEquals("spotify:track:1xHutdgil2xlhdNLOL8Cr9", c.getString(0))
            assertTrue("isrc is still unknown after migrating", c.isNull(1))
            assertTrue("never attempted", c.isNull(2))
            assertEquals(0, c.getInt(3))
            assertTrue(c.isNull(4))
        }

        migrated.query("SELECT COUNT(*) FROM tracks").use { c ->
            c.moveToFirst()
            assertEquals(1, c.getInt(0))
        }

        // The archive tables arrive empty rather than absent.
        for (table in listOf("likes", "like_events", "sync_state")) {
            migrated.query("SELECT COUNT(*) FROM $table").use { c ->
                c.moveToFirst()
                assertEquals("$table should exist and be empty", 0, c.getInt(0))
            }
        }
        migrated.close()
    }

    /**
     * The point of the whole migration: deleting a canonical track that still
     * has listening history must fail loudly instead of taking the history with
     * it.
     *
     * Run against a real Room-built v2 database rather than the migration
     * helper's connection, because it is Room that turns foreign-key
     * enforcement on — a raw connection would happily allow the delete and the
     * test would prove nothing.
     */
    @Test
    fun restrictBlocksDeletingATrackThatStillHasSegments() = runBlocking {
        val db = freshV2Database()
        try {
            val dao = db.dao()
            dao.recordSegment(
                trackKey = trackKeyOf("Afterthought", "Joji", "Ballads 1"),
                title = "Afterthought",
                artist = "Joji",
                album = "Ballads 1",
                durationMs = 242_000,
                service = SERVICE_SPOTIFY,
                serviceTrackId = "spotify:track:4h3K5he5ItFqJB1MVHMKJV",
                segment = sampleSegment(),
            )

            val trackId = dao.allTracks().single().id

            assertThrows(
                "deleting a track with listening history must be refused",
                SQLiteConstraintException::class.java,
            ) {
                runBlocking {
                    db.openHelper.writableDatabase.execSQL(
                        "DELETE FROM tracks WHERE id = $trackId",
                    )
                }
            }

            assertEquals("nothing was deleted", 1, dao.allSegments().size)
            assertEquals(1, dao.allTracks().size)
        } finally {
            db.close()
        }
    }

    /**
     * The other half of RESTRICT: a service identifier may not be deleted out
     * from under the segments that reference it.
     *
     * Under v1 this key was SET NULL, so the delete succeeded and every segment
     * quietly forgot which Spotify recording it had been. The segments kept
     * their listened time and lost their identity, which is the subtler of the
     * two data losses and the reason this key changed too.
     */
    @Test
    fun restrictBlocksDeletingAServiceTrackStillReferencedBySegments() = runBlocking {
        val db = freshV2Database()
        try {
            val dao = db.dao()
            dao.recordSegment(
                trackKey = trackKeyOf("Afterthought", "Joji", "Ballads 1"),
                title = "Afterthought",
                artist = "Joji",
                album = "Ballads 1",
                durationMs = 242_000,
                service = SERVICE_SPOTIFY,
                serviceTrackId = "spotify:track:4h3K5he5ItFqJB1MVHMKJV",
                segment = sampleSegment(),
            )
            val serviceRowId = dao.allServiceTracks().single().id

            assertThrows(
                SQLiteConstraintException::class.java,
            ) {
                db.openHelper.writableDatabase.execSQL(
                    "DELETE FROM service_tracks WHERE id = $serviceRowId",
                )
            }

            assertEquals(
                "the segment still knows which Spotify recording it was",
                serviceRowId,
                dao.allSegments().single().serviceTrackRowId,
            )
        } finally {
            db.close()
        }
    }

    /**
     * `deleteEverything` has to clear children before parents now that nothing
     * cascades. If the order is wrong this throws instead of deleting, so the
     * test is really "does the debug wipe still work at all under RESTRICT".
     */
    @Test
    fun deleteEverythingStillWorksUnderRestrict() = runBlocking {
        val db = freshV2Database()
        try {
            val dao = db.dao()
            dao.recordSegment(
                trackKey = trackKeyOf("Afterthought", "Joji", "Ballads 1"),
                title = "Afterthought",
                artist = "Joji",
                album = "Ballads 1",
                durationMs = 242_000,
                service = SERVICE_SPOTIFY,
                serviceTrackId = "spotify:track:4h3K5he5ItFqJB1MVHMKJV",
                segment = sampleSegment(),
            )

            dao.deleteEverything()

            assertEquals(0, dao.allSegments().size)
            assertEquals(0, dao.allServiceTracks().size)
            assertEquals(0, dao.allTracks().size)
        } finally {
            db.close()
        }
    }

    // --- v3 -> v4 ------------------------------------------------------------

    /**
     * Builds a populated v3 database, migrates it to v4, and checks that every
     * segment came through with its numbers intact and marked as captured.
     *
     * v4 makes `startPositionMs`, `endPositionMs`, `forwardSeekCount`,
     * `seekedForwardMs` and `lastSampleAgeMs` nullable so that imported history
     * can share this table without any column being filled with a value nobody
     * observed (invariant 1b). SQLite cannot relax a NOT NULL in place, so this
     * is another full table rebuild — the same risk as v2, tested the same way.
     *
     * The two rows are chosen to be awkward: one is the seek-to-end row whose
     * `endPositionMs` and `listenedMs` disagree by ten to one, so a copy that
     * shifted a column would show; the other is a replay whose jump pair must
     * survive, since that pair is what lets the replay threshold still be
     * chosen at read time.
     */
    @Test
    fun migrate3To4_everySegmentSurvivesAndIsMarkedCaptured() {
        helper.createDatabase(TEST_DB, 3).use { db ->
            db.execSQL(
                """
                INSERT INTO tracks
                    (id, trackKey, title, artist, album, durationMs, firstSeenAt, lastSeenAt)
                VALUES (1, 'electro swingity|tonight we rise|singles', 'Electro Swingity',
                        'Tonight We Rise', 'Singles', $SEEKED_DURATION, 1000, 2000)
                """.trimIndent(),
            )
            db.execSQL(
                """
                INSERT INTO service_tracks
                    (id, trackId, service, serviceTrackId, isrc, isrcLookupAt, isrcLookupAttempts,
                     isrcLookupError, durationMs, firstSeenAt, lastSeenAt)
                VALUES (1, 1, 'spotify', 'spotify:track:1xHutdgil2xlhdNLOL8Cr9', 'GBAYE1500860',
                        1500, 1, NULL, $SEEKED_DURATION, 1000, 2000)
                """.trimIndent(),
            )
            db.execSQL(
                """
                INSERT INTO listening_segments
                    (id, trackId, serviceTrackRowId, appPackage, deviceId, startedAtMs, endedAtMs,
                     startPositionMs, endPositionMs, listenedMs, trackDurationMs,
                     forwardSeekCount, seekedForwardMs, endReason, endJumpFromMs, endJumpToMs,
                     lastSampleAgeMs, createdAt)
                VALUES (1, 1, 1, 'com.spotify.music', 'test-device', 1000, 2000,
                        0, $SEEKED_END_POSITION, $SEEKED_LISTENED, $SEEKED_DURATION,
                        1, 180000, 'TRACK_CHANGE', NULL, NULL, 500, 2000)
                """.trimIndent(),
            )
            db.execSQL(
                """
                INSERT INTO listening_segments
                    (id, trackId, serviceTrackRowId, appPackage, deviceId, startedAtMs, endedAtMs,
                     startPositionMs, endPositionMs, listenedMs, trackDurationMs,
                     forwardSeekCount, seekedForwardMs, endReason, endJumpFromMs, endJumpToMs,
                     lastSampleAgeMs, createdAt)
                VALUES (2, 1, NULL, 'com.spotify.music', 'test-device', 3000, 4000,
                        0, 31250, 31250, $SEEKED_DURATION,
                        0, 0, 'POSITION_JUMP_BACK', 31250, 0, 31250, 4000)
                """.trimIndent(),
            )
            db.execSQL(
                """
                INSERT INTO track_merges
                    (id, survivorTrackId, mergedTrackKey, mergedTitle, mergedArtist, mergedAlbum,
                     isrc, segmentsMoved, serviceRowsMoved, mergedAt)
                VALUES (1, 1, 'dracula|deadbeat|deadbeat', 'Dracula', 'Deadbeat', 'Deadbeat',
                        'USQX92504223', 3, 1, 5000)
                """.trimIndent(),
            )
        }

        val migrated = helper.runMigrationsAndValidate(TEST_DB, 4, true)

        migrated.query("SELECT COUNT(*) FROM listening_segments").use { c ->
            c.moveToFirst()
            assertEquals("both segments must survive the table rebuild", 2, c.getInt(0))
        }

        migrated.query(
            """
            SELECT trackId, serviceTrackRowId, appPackage, deviceId, startedAtMs, endedAtMs,
                   startPositionMs, endPositionMs, listenedMs, trackDurationMs,
                   forwardSeekCount, seekedForwardMs, endReason, lastSampleAgeMs, createdAt,
                   source, sourceEndReason
              FROM listening_segments WHERE id = 1
            """.trimIndent(),
        ).use { c ->
            assertTrue(c.moveToFirst())
            assertEquals(1L, c.getLong(c.getColumnIndexOrThrow("trackId")))
            assertEquals(1L, c.getLong(c.getColumnIndexOrThrow("serviceTrackRowId")))
            assertEquals("com.spotify.music", c.getString(c.getColumnIndexOrThrow("appPackage")))
            assertEquals("test-device", c.getString(c.getColumnIndexOrThrow("deviceId")))
            assertEquals(1000L, c.getLong(c.getColumnIndexOrThrow("startedAtMs")))
            assertEquals(2000L, c.getLong(c.getColumnIndexOrThrow("endedAtMs")))
            assertEquals(0L, c.getLong(c.getColumnIndexOrThrow("startPositionMs")))
            assertEquals(
                "position reached must not be confused with time listened",
                SEEKED_END_POSITION,
                c.getLong(c.getColumnIndexOrThrow("endPositionMs")),
            )
            assertEquals(SEEKED_LISTENED, c.getLong(c.getColumnIndexOrThrow("listenedMs")))
            assertEquals(SEEKED_DURATION, c.getLong(c.getColumnIndexOrThrow("trackDurationMs")))
            assertEquals(1, c.getInt(c.getColumnIndexOrThrow("forwardSeekCount")))
            assertEquals(180_000L, c.getLong(c.getColumnIndexOrThrow("seekedForwardMs")))
            assertEquals("TRACK_CHANGE", c.getString(c.getColumnIndexOrThrow("endReason")))
            assertEquals(500L, c.getLong(c.getColumnIndexOrThrow("lastSampleAgeMs")))
            assertEquals(2000L, c.getLong(c.getColumnIndexOrThrow("createdAt")))

            // The whole point of the new column's default: a row written before
            // there was any such thing as an import is a captured row.
            assertEquals("CAPTURE", c.getString(c.getColumnIndexOrThrow("source")))
            assertTrue(
                "a captured row has no export reason code",
                c.isNull(c.getColumnIndexOrThrow("sourceEndReason")),
            )
        }

        // The replay keeps its jump pair, which is what lets the replay
        // threshold still be a read-time decision over history already stored.
        migrated.query(
            "SELECT endReason, endJumpFromMs, endJumpToMs, serviceTrackRowId, source " +
                "FROM listening_segments WHERE id = 2",
        ).use { c ->
            assertTrue(c.moveToFirst())
            assertEquals("POSITION_JUMP_BACK", c.getString(0))
            assertEquals(31_250L, c.getLong(1))
            assertEquals(0L, c.getLong(2))
            assertTrue("a segment with no service id must stay null", c.isNull(3))
            assertEquals("CAPTURE", c.getString(4))
        }

        // Nothing else in the database was disturbed, including the ISRC that
        // Phase 2 paid a request for and the merge audit trail.
        migrated.query("SELECT isrc, isrcLookupAttempts FROM service_tracks WHERE id = 1").use { c ->
            assertTrue(c.moveToFirst())
            assertEquals("GBAYE1500860", c.getString(0))
            assertEquals(1, c.getInt(1))
        }
        migrated.query("SELECT COUNT(*) FROM track_merges").use { c ->
            c.moveToFirst()
            assertEquals(1, c.getInt(0))
        }
        migrated.query("SELECT COUNT(*) FROM tracks").use { c ->
            c.moveToFirst()
            assertEquals(1, c.getInt(0))
        }
        migrated.close()
    }

    /**
     * After migrating, the table must actually accept a row with the nulls —
     * otherwise v4 would validate as the right shape and still refuse every
     * import.
     */
    @Test
    fun migrate3To4_acceptsAnImportedRowWithNoPositions() {
        helper.createDatabase(TEST_DB, 3).use { db ->
            db.execSQL(
                """
                INSERT INTO tracks
                    (id, trackKey, title, artist, album, durationMs, firstSeenAt, lastSeenAt)
                VALUES (1, 'a|b|c', 'A', 'B', 'C', 200000, 1000, 2000)
                """.trimIndent(),
            )
        }

        val migrated = helper.runMigrationsAndValidate(TEST_DB, 4, true)

        migrated.execSQL(
            """
            INSERT INTO listening_segments
                (trackId, serviceTrackRowId, appPackage, deviceId, startedAtMs, endedAtMs,
                 startPositionMs, endPositionMs, listenedMs, trackDurationMs,
                 forwardSeekCount, seekedForwardMs, endReason, endJumpFromMs, endJumpToMs,
                 lastSampleAgeMs, createdAt, source, sourceEndReason)
            VALUES (1, NULL, 'com.spotify.music', 'spotify-history-import', 1000, 181000,
                    NULL, NULL, 180000, 200000,
                    NULL, NULL, 'IMPORTED', NULL, NULL,
                    NULL, 9000, 'IMPORT_SPOTIFY_HISTORY', 'trackdone')
            """.trimIndent(),
        )

        migrated.query(
            "SELECT startPositionMs, endPositionMs, forwardSeekCount, seekedForwardMs, " +
                "lastSampleAgeMs, listenedMs, source, sourceEndReason, endReason " +
                "FROM listening_segments",
        ).use { c ->
            assertTrue(c.moveToFirst())
            assertTrue("imported rows record no position", c.isNull(0))
            assertTrue(c.isNull(1))
            assertTrue("imported rows saw no seeks", c.isNull(2))
            assertTrue(c.isNull(3))
            assertTrue("imported rows rest on no extrapolation", c.isNull(4))
            assertEquals(180_000L, c.getLong(5))
            assertEquals("IMPORT_SPOTIFY_HISTORY", c.getString(6))
            assertEquals("trackdone", c.getString(7))
            assertEquals("IMPORTED", c.getString(8))
        }
        migrated.close()
    }

    // --- v4 -> v5 ------------------------------------------------------------

    /**
     * v5 only adds tables, so unlike v2 and v4 nothing here can lose history.
     * The test is still worth having for the opposite reason: to prove that it
     * really is additive, and that the existing rows — including the ones v4
     * just rebuilt — are untouched by it.
     */
    @Test
    fun migrate4To5_addsTheNewTablesAndDisturbsNothing() {
        helper.createDatabase(TEST_DB, 4).use { db ->
            db.execSQL(
                """
                INSERT INTO tracks
                    (id, trackKey, title, artist, album, durationMs, firstSeenAt, lastSeenAt)
                VALUES (1, 'metadata|willix|metadata', 'Metadata', 'Willix', 'Metadata',
                        109000, 1000, 2000)
                """.trimIndent(),
            )
            db.execSQL(
                """
                INSERT INTO service_tracks
                    (id, trackId, service, serviceTrackId, isrc, isrcLookupAt, isrcLookupAttempts,
                     isrcLookupError, durationMs, firstSeenAt, lastSeenAt)
                VALUES (1, 1, 'spotify', 'spotify:track:4h3K5he5ItFqJB1MVHMKJV', 'GBAYE1500860',
                        1500, 1, NULL, 109000, 1000, 2000)
                """.trimIndent(),
            )
            // One captured row and one imported row, so both shapes v4 allows
            // are present across the migration.
            db.execSQL(
                """
                INSERT INTO listening_segments
                    (id, trackId, serviceTrackRowId, appPackage, deviceId, startedAtMs, endedAtMs,
                     startPositionMs, endPositionMs, listenedMs, trackDurationMs,
                     forwardSeekCount, seekedForwardMs, endReason, endJumpFromMs, endJumpToMs,
                     lastSampleAgeMs, createdAt, source, sourceEndReason)
                VALUES (1, 1, 1, 'com.spotify.music', 'test-device', 1000, 110000,
                        0, 109000, 109000, 109000, 0, 0, 'TRACK_CHANGE', NULL, NULL,
                        100, 110000, 'CAPTURE', NULL)
                """.trimIndent(),
            )
            db.execSQL(
                """
                INSERT INTO listening_segments
                    (id, trackId, serviceTrackRowId, appPackage, deviceId, startedAtMs, endedAtMs,
                     startPositionMs, endPositionMs, listenedMs, trackDurationMs,
                     forwardSeekCount, seekedForwardMs, endReason, endJumpFromMs, endJumpToMs,
                     lastSampleAgeMs, createdAt, source, sourceEndReason)
                VALUES (2, 1, 1, 'com.spotify.music', 'spotify-history-import', 500000, 609000,
                        NULL, NULL, 109000, 0, NULL, NULL, 'IMPORTED', NULL, NULL,
                        NULL, 700000, 'IMPORT_SPOTIFY_HISTORY', 'trackdone')
                """.trimIndent(),
            )
            db.execSQL(
                """
                INSERT INTO likes
                    (id, serviceTrackRowId, serviceAddedAtMs, firstSeenLikedAt, lastSeenLikedAt,
                     unlikedAt)
                VALUES (1, 1, 1600000000000, 1700000000000, 1700000000000, NULL)
                """.trimIndent(),
            )
            db.execSQL(
                """
                INSERT INTO sync_state (`key`, valueMs, valueText)
                VALUES ('scoring_parameters', 1700000000000, '{"halfLifeDays":45.0}')
                """.trimIndent(),
            )
        }

        val migrated = helper.runMigrationsAndValidate(TEST_DB, 5, true)

        // The four new tables exist and are empty, rather than absent.
        for (table in listOf("scores", "evergreen_membership", "snapshots", "snapshot_entries")) {
            migrated.query("SELECT COUNT(*) FROM $table").use { c ->
                c.moveToFirst()
                assertEquals("$table should exist and be empty", 0, c.getInt(0))
            }
        }

        // Everything that was there before still is, both segment shapes intact.
        migrated.query("SELECT COUNT(*) FROM listening_segments").use { c ->
            c.moveToFirst()
            assertEquals(2, c.getInt(0))
        }
        migrated.query(
            "SELECT source, startPositionMs, listenedMs, sourceEndReason " +
                "FROM listening_segments WHERE id = 2",
        ).use { c ->
            assertTrue(c.moveToFirst())
            assertEquals("IMPORT_SPOTIFY_HISTORY", c.getString(0))
            assertTrue("the imported row's nulls survive", c.isNull(1))
            assertEquals(109_000L, c.getLong(2))
            assertEquals("trackdone", c.getString(3))
        }
        migrated.query("SELECT serviceAddedAtMs FROM likes WHERE id = 1").use { c ->
            assertTrue(c.moveToFirst())
            assertEquals(
                "Spotify's added_at is what likes decay from, so it must survive",
                1_600_000_000_000L,
                c.getLong(0),
            )
        }
        migrated.query(
            "SELECT valueText FROM sync_state WHERE `key` = 'scoring_parameters'",
        ).use { c ->
            assertTrue(c.moveToFirst())
            assertEquals("""{"halfLifeDays":45.0}""", c.getString(0))
        }
        migrated.close()
    }

    /**
     * The new tables must actually accept what Phase 3 will put in them,
     * including the snapshot's parameters JSON — without which a snapshot's
     * scores become unreadable the first time the scoring is retuned.
     */
    @Test
    fun migrate4To5_acceptsScoresMembershipAndSnapshots() {
        helper.createDatabase(TEST_DB, 4).use { db ->
            db.execSQL(
                """
                INSERT INTO tracks
                    (id, trackKey, title, artist, album, durationMs, firstSeenAt, lastSeenAt)
                VALUES (1, 'a|b|c', 'A', 'B', 'C', 200000, 1000, 2000)
                """.trimIndent(),
            )
        }

        val migrated = helper.runMigrationsAndValidate(TEST_DB, 5, true)

        migrated.execSQL(
            "INSERT INTO scores (trackId, score, rank, computedAt, parametersHash) " +
                "VALUES (1, 4.25, 7, 1700000000000, 'abc123')",
        )
        migrated.execSQL(
            """
            INSERT INTO evergreen_membership
                (trackId, joinedAt, leftAt, joinReason, leaveReason, rankAtJoin, rankAtLeave)
            VALUES (1, 1700000000000, NULL, 'JOINED_BY_RANK', NULL, 7, NULL)
            """.trimIndent(),
        )
        migrated.execSQL(
            """
            INSERT INTO snapshots
                (id, monthKey, label, takenAt, parametersJson, playlistSize, trackCount,
                 exportedPlaylistId, exportedAt)
            VALUES (1, '2026-08', '2026 August', 1700000000000, '{"halfLifeDays":45.0}',
                    100, 380, NULL, NULL)
            """.trimIndent(),
        )
        migrated.execSQL(
            """
            INSERT INTO snapshot_entries
                (snapshotId, trackId, rank, score, serviceTrackId, title, artist, inPlaylist)
            VALUES (1, 1, 7, 4.25, 'spotify:track:aaa', 'A', 'B', 1)
            """.trimIndent(),
        )

        migrated.query("SELECT score, rank, parametersHash FROM scores WHERE trackId = 1").use { c ->
            assertTrue(c.moveToFirst())
            assertEquals(4.25, c.getDouble(0), 1e-9)
            assertEquals(7, c.getInt(1))
            assertEquals("abc123", c.getString(2))
        }
        migrated.query("SELECT parametersJson, monthKey FROM snapshots WHERE id = 1").use { c ->
            assertTrue(c.moveToFirst())
            assertEquals("""{"halfLifeDays":45.0}""", c.getString(0))
            assertEquals("2026-08", c.getString(1))
        }
        migrated.query("SELECT inPlaylist, serviceTrackId FROM snapshot_entries").use { c ->
            assertTrue(c.moveToFirst())
            assertEquals(1, c.getInt(0))
            assertEquals("spotify:track:aaa", c.getString(1))
        }

        // One snapshot per month, so the daily worker can run harmlessly.
        assertThrows(SQLiteConstraintException::class.java) {
            migrated.execSQL(
                """
                INSERT INTO snapshots
                    (monthKey, label, takenAt, parametersJson, playlistSize, trackCount)
                VALUES ('2026-08', '2026 August', 1700000000001, '{}', 100, 380)
                """.trimIndent(),
            )
        }
        migrated.close()
    }

    /**
     * v6 adds `parameter_history` and must disturb nothing.
     *
     * The populated database here carries the two rows that matter to the new
     * table's reason for existing: the single `sync_state` row holding the
     * current scoring parameters, which is the value the log exists because it
     * gets overwritten, and a snapshot with its own copy of the parameters,
     * which is the only place past values survived before now.
     */
    @Test
    fun migrate5To6_addsTheParameterLogAndDisturbsNothing() {
        helper.createDatabase(TEST_DB, 5).use { db ->
            db.execSQL(
                """
                INSERT INTO tracks
                    (id, trackKey, title, artist, album, durationMs, firstSeenAt, lastSeenAt)
                VALUES (1, 'metadata|willix|metadata', 'Metadata', 'Willix', 'Metadata',
                        109000, 1000, 2000)
                """.trimIndent(),
            )
            db.execSQL(
                """
                INSERT INTO sync_state (`key`, valueMs, valueText)
                VALUES ('scoring_parameters', NULL, '{"halfLifeDays":45.0,"likeWeight":3.0}')
                """.trimIndent(),
            )
            db.execSQL(
                """
                INSERT INTO scores (trackId, score, rank, computedAt, parametersHash)
                VALUES (1, 4.25, 7, 1700000000000, 'abc123')
                """.trimIndent(),
            )
            db.execSQL(
                """
                INSERT INTO snapshots
                    (id, monthKey, label, takenAt, parametersJson, playlistSize, trackCount,
                     exportedPlaylistId, exportedAt)
                VALUES (1, '2026-08', '2026 August', 1700000000000,
                        '{"halfLifeDays":45.0,"likeWeight":3.0}', 100, 380, NULL, NULL)
                """.trimIndent(),
            )
            db.execSQL(
                """
                INSERT INTO snapshot_entries
                    (snapshotId, trackId, rank, score, serviceTrackId, title, artist, inPlaylist)
                VALUES (1, 1, 7, 4.25, 'spotify:track:aaa', 'Metadata', 'Willix', 1)
                """.trimIndent(),
            )
            db.execSQL(
                """
                INSERT INTO evergreen_membership
                    (trackId, joinedAt, leftAt, joinReason, leaveReason, rankAtJoin, rankAtLeave)
                VALUES (1, 1700000000000, NULL, 'JOINED_BY_RANK', NULL, 7, NULL)
                """.trimIndent(),
            )
        }

        val migrated = helper.runMigrationsAndValidate(TEST_DB, 6, true)

        migrated.query("SELECT COUNT(*) FROM parameter_history").use { c ->
            c.moveToFirst()
            assertEquals("parameter_history should exist and be empty", 0, c.getInt(0))
        }

        // Nothing else moved. The parameters in force and the snapshot's own
        // copy of them are the two rows this table is about, so both are read
        // back rather than merely counted.
        migrated.query(
            "SELECT valueText FROM sync_state WHERE `key` = 'scoring_parameters'",
        ).use { c ->
            assertTrue(c.moveToFirst())
            assertEquals("""{"halfLifeDays":45.0,"likeWeight":3.0}""", c.getString(0))
        }
        migrated.query("SELECT parametersJson FROM snapshots WHERE id = 1").use { c ->
            assertTrue(c.moveToFirst())
            assertEquals("""{"halfLifeDays":45.0,"likeWeight":3.0}""", c.getString(0))
        }
        migrated.query("SELECT score, parametersHash FROM scores WHERE trackId = 1").use { c ->
            assertTrue(c.moveToFirst())
            assertEquals(4.25, c.getDouble(0), 1e-9)
            assertEquals("abc123", c.getString(1))
        }
        migrated.query("SELECT COUNT(*) FROM snapshot_entries").use { c ->
            c.moveToFirst()
            assertEquals(1, c.getInt(0))
        }
        migrated.query("SELECT COUNT(*) FROM evergreen_membership WHERE leftAt IS NULL").use { c ->
            c.moveToFirst()
            assertEquals(1, c.getInt(0))
        }

        // The new table takes rows, including the null previousJson the first
        // entry is allowed to carry.
        migrated.execSQL(
            """
            INSERT INTO parameter_history (changedAt, parametersJson, parametersHash, previousJson)
            VALUES (1700000000001, '{"halfLifeDays":30.0}', 'def456', NULL)
            """.trimIndent(),
        )
        migrated.query(
            "SELECT changedAt, parametersJson, parametersHash, previousJson FROM parameter_history",
        ).use { c ->
            assertTrue(c.moveToFirst())
            assertEquals(1_700_000_000_001L, c.getLong(0))
            assertEquals("""{"halfLifeDays":30.0}""", c.getString(1))
            assertEquals("def456", c.getString(2))
            assertTrue("the first entry may have no predecessor", c.isNull(3))
        }
        migrated.close()
    }

